package com.example.learnjava2026.Section3;

public class Lesson15 {
    public static void main(String[] args) {
        int myFirstNumber = 5;
        System.out.println(myFirstNumber);

        // gán giá trị myFirstNumber = 10
        myFirstNumber = 10;
        System.out.println(myFirstNumber);

        System.out.println(5+10);

        // thực hiện phép tính với myFirstNumber vừa được gán
        int mySecondNumber = 25;
        System.out.println(myFirstNumber+mySecondNumber);
    }
}
